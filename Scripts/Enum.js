    GetMoleculeAtoms(Atom) {
        const StartIdx = Objects.indexOf(Atom);
        if (StartIdx < 0) return [Atom];
        const Neighbors = new Map();
        for (const Key of this.ActiveBondPairs) {
            const [A, B] = Key.split("_").map(Number);
            if (!Neighbors.has(A)) Neighbors.set(A, []);
            if (!Neighbors.has(B)) Neighbors.set(B, []);
            Neighbors.get(A).push(B);
            Neighbors.get(B).push(A);
        }
        const Visited = new Set();
        const Queue = [StartIdx];
        Visited.add(StartIdx);
        while (Queue.length) {
            const Cur = Queue.shift();
            const Ns = Neighbors.get(Cur) || [];
            for (const N of Ns) if (!Visited.has(N)) { Visited.add(N); Queue.push(N); }
        }
        return [...Visited].map((i) => Objects[i]).filter(Boolean);
    }

