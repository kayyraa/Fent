    ComputePartialCharges() {
        for (const Obj of Objects) {
            Obj.PartialCharge = Obj.ExtraCharge || 0;
            Obj.Dipole = [0, 0, 0];
        }
        for (const Key of this.ActiveBondPairs) {
            const Data = this.BondData.get(Key);
            if (!Data) continue;
            const AtomA = Objects[Data.IndexA];
            const AtomB = Objects[Data.IndexB];
            if (!AtomA || !AtomB) continue;
            const EnA = AtomA.Atom.Electronegativity ?? 2.2;
            const EnB = AtomB.Atom.Electronegativity ?? 2.2;
            const OrderMul = 1 + ((Data.order || 1) - 1) * 0.4;
            const Delta = (EnB - EnA) * 0.18 * OrderMul;
            AtomA.PartialCharge += Delta;
            AtomB.PartialCharge -= Delta;
            const Dx = AtomB.Position[0] - AtomA.Position[0];
            const Dy = AtomB.Position[1] - AtomA.Position[1];
            const Dz = AtomB.Position[2] - AtomA.Position[2];
            const Mag = Math.sqrt(Dx*Dx + Dy*Dy + Dz*Dz) + 0.01;
            const Scale = Delta * 12;
            AtomA.Dipole[0] += (Dx/Mag)*Scale;
            AtomA.Dipole[1] += (Dy/Mag)*Scale;
            AtomA.Dipole[2] += (Dz/Mag)*Scale;
            AtomB.Dipole[0] += (Dx/Mag)*Scale;
            AtomB.Dipole[1] += (Dy/Mag)*Scale;
            AtomB.Dipole[2] += (Dz/Mag)*Scale;
        }
    }

