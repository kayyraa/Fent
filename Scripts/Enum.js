globalThis.Atom = (Key, Position, Velocity) => {
    const DefaultData = {
        AtomicRadius: 50,
        Valence: RealisticValence[Key] ?? 1,
        Electronegativity: 2.1,
        AtomicMass: 1.0,
        Name: Key
    };
    const Source = (typeof Atoms !== "undefined" && Atoms[Key]) ? Atoms[Key] : DefaultData;
    const AtomData = { ...Source, Valence: RealisticValence[Key] ?? Source.Valence ?? 1 };

    let Protons = AtomData.AtomicNumber || 1;
    let Neutrons = Math.max(0, Math.round(AtomData.AtomicMass || Protons * 2) - Protons);
    if (globalThis.Chemistry && globalThis.Chemistry.GetIsotope) {
        const Isotope = globalThis.Chemistry.GetIsotope(Key, AtomData);
        Protons = Isotope[0];
        Neutrons = Isotope[1];
    }

    let Stable = true;
    if (globalThis.Chemistry && globalThis.Chemistry.DecayProbability) {
        Stable = globalThis.Chemistry.DecayProbability(Protons, Neutrons) === 0;
    }

    const RadiusPm = AtomData.AtomicRadius ?? 100;
    const BaseScale = Math.max(8, RadiusPm * 0.6 * 0.3);
    const MassInv = 1 / Math.max(0.0001, AtomData.AtomicMass || 1);

    const Chem = globalThis.Chemistry;
    const Noble = Chem ? Chem.IsNoble(Key) : false;

    const AtomObject = {
        Key: Key,
        Position: [Position[0] || 0, Position[1] || 0, Position[2] || 0],
        Velocity: [Velocity[0] || 0, Velocity[1] || 0, Velocity[2] || 0],
        Force: [0, 0, 0],
        Atom: AtomData,
        Mesh: Enum.Mesh.Sphere,
        Rotation: 0,
        Protons: Protons,
        Neutrons: Neutrons,
        Stable: Stable,
        BaseScale: BaseScale,
        MassInv: MassInv,
        EffRadius: RadiusPm * 0.35,
        AtomColor: globalThis.ElementColors[Key] || [0.7, 0.7, 0.7],
        Noble: Noble,
        ElectronWant: Chem ? Chem.ElectronWant(Key) : 0.35,
        ElectronDonate: Chem ? Chem.ElectronDonate(Key) : 0.35,
        QuantumShells: Chem ? Chem.QuantumShells(Key) : [],
        Polarizability: Chem ? Chem.GetPolarizability(Key) : 1.0,
        BondOrderSum: 0,
        BondSatisfaction: 0
    };

    Objects.push(AtomObject);
    return AtomObject;
};

function CreateTextTexture(Gl, Text) {
    const Canvas = document.createElement("canvas");
    Canvas.width = 512;
    Canvas.height = 256;
    const Ctx = Canvas.getContext("2d");
    Ctx.clearRect(0, 0, Canvas.width, Canvas.height);
    Ctx.font = "bold 96px 'Cascadia Mono', monospace, sans-serif";
    Ctx.textAlign = "center";
    Ctx.textBaseline = "middle";
    Ctx.fillStyle = "#ffffff";
    Ctx.strokeStyle = "#000000";
    Ctx.lineWidth = 12;
    for (const X of [Canvas.width * 0.25, Canvas.width * 0.75]) {
        Ctx.strokeText(Text, X, Canvas.height * 0.5);
        Ctx.fillText(Text, X, Canvas.height * 0.5);
    }
    const Texture = Gl.createTexture();
    Gl.bindTexture(Gl.TEXTURE_2D, Texture);
    Gl.texImage2D(Gl.TEXTURE_2D, 0, Gl.RGBA, Gl.RGBA, Gl.UNSIGNED_BYTE, Canvas);
    Gl.generateMipmap(Gl.TEXTURE_2D);
    Gl.texParameteri(Gl.TEXTURE_2D, Gl.TEXTURE_MIN_FILTER, Gl.LINEAR_MIPMAP_LINEAR);
    Gl.texParameteri(Gl.TEXTURE_2D, Gl.TEXTURE_MAG_FILTER, Gl.LINEAR);
    Gl.texParameteri(Gl.TEXTURE_2D, Gl.TEXTURE_WRAP_S, Gl.REPEAT);
    Gl.texParameteri(Gl.TEXTURE_2D, Gl.TEXTURE_WRAP_T, Gl.CLAMP_TO_EDGE);
    return Texture;
}

const VertexShaderSource = `
attribute vec3 APosition;
attribute vec3 ANormal;
uniform mat4 UModel;
uniform mat4 UView;
uniform mat4 UProjection;
varying vec3 VNormal;
varying vec3 VWorldPosition;
varying vec3 VLocalPosition;
void main() {
    VLocalPosition = APosition;
    vec4 WorldPosition = UModel * vec4(APosition, 1.0);
    VWorldPosition = WorldPosition.xyz;
    VNormal = mat3(UModel) * ANormal;
    gl_Position = UProjection * UView * WorldPosition;
}
`;

const FragmentShaderSource = `
precision mediump float;
varying vec3 VNormal;
varying vec3 VWorldPosition;
varying vec3 VLocalPosition;
uniform vec3 UColor;
uniform vec3 ULightPosition;
uniform vec3 UCameraPosition;
uniform sampler2D UTexture;
const float PI = 3.14159265359;
void main() {
    vec3 LocalNorm = normalize(VLocalPosition);
    float U = 0.5 - atan(LocalNorm.z, LocalNorm.x) / (2.0 * PI);
    float V = 0.5 - asin(clamp(LocalNorm.y, -1.0, 1.0)) / PI;
    vec4 TexColor = texture2D(UTexture, vec2(U, V));
    vec3 Normal = normalize(VNormal);
    vec3 LightDirection = normalize(ULightPosition - VWorldPosition);
    vec3 ViewDirection = normalize(UCameraPosition - VWorldPosition);
    vec3 HalfVector = normalize(LightDirection + ViewDirection);
    float NdotL = max(dot(Normal, LightDirection), 0.0);
    float Diffuse;
    if (NdotL > 0.8) Diffuse = 1.0;
    else if (NdotL > 0.4) Diffuse = 0.6;
    else if (NdotL > 0.15) Diffuse = 0.35;
    else Diffuse = 0.15;
    float NdotH = max(dot(Normal, HalfVector), 0.0);
    float SpecularStrength = pow(NdotH, 32.0);
    float Specular = step(0.5, SpecularStrength) * 0.6;
    float Edge = dot(ViewDirection, Normal);
    float Silhouette = step(0.25, Edge);
    vec3 BaseColor = mix(UColor, TexColor.rgb, TexColor.a);
    vec3 FinalColor = (BaseColor * Diffuse + vec3(1.0) * Specular) * Silhouette;
    gl_FragColor = vec4(FinalColor, 1.0);
}
`;

