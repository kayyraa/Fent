globalThis.MultiplyMatrices = function(A, B) {
    const Result = new Float32Array(16);
    for (let Row = 0; Row < 4; Row++) {
        for (let Column = 0; Column < 4; Column++) {
            let Sum = 0;
            for (let Index = 0; Index < 4; Index++) Sum += A[Index * 4 + Row] * B[Column * 4 + Index];
            Result[Column * 4 + Row] = Sum;
        }
    }
    return Result;
};
globalThis.Subtract3 = (A, B) => [A[0]-B[0], A[1]-B[1], A[2]-B[2]];
globalThis.Cross3 = (A, B) => [A[1]*B[2]-A[2]*B[1], A[2]*B[0]-A[0]*B[2], A[0]*B[1]-A[1]*B[0]];
globalThis.Dot3 = (A, B) => A[0]*B[0] + A[1]*B[1] + A[2]*B[2];
globalThis.Normalize3 = (V) => {
    const Length = Math.sqrt(Dot3(V, V));
    if (Length === 0) return [0, 0, 0];
    return [V[0]/Length, V[1]/Length, V[2]/Length];
};

